package com.holberton.realestate.checks;

import java.util.Set;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Order;
import org.junit.jupiter.api.Test;

import com.holberton.realestate.checks.support.ApiCheck;
import com.holberton.realestate.checks.support.Expect;
import com.holberton.realestate.checks.support.Reflect;
import com.holberton.realestate.checks.support.Response;
import com.holberton.realestate.checks.support.Schema;

/** Task 3: the entity and the database schema. */
class Task03Test extends ApiCheck {

    @Order(1)
    @Test
    @DisplayName("the table PROPERTIES exists in the database")
    void tableExists() {
        Expect.isTrue(schema().hasTable("properties"),
                "expected a table PROPERTIES in the database but found " + schema().tables());
    }

    @Order(2)
    @Test
    @DisplayName("PROPERTIES has a primary key column ID generated by the database")
    void primaryKey() {
        Set<String> keys = schema().primaryKeyColumns("properties");
        Expect.isTrue(keys.contains("ID"),
                "expected ID to be the primary key of PROPERTIES but got " + keys);
        Class<?> property = Reflect.require(Reflect.PACKAGE + ".model.Property");
        boolean generated = false;
        for (java.lang.reflect.Field field : property.getDeclaredFields()) {
            if (Reflect.hasAnnotation(field, "jakarta.persistence.Id")) {
                generated = Reflect.hasAnnotation(field, "jakarta.persistence.GeneratedValue");
            }
        }
        Expect.isTrue(generated, "expected the id of Property to be annotated with @Id and @GeneratedValue");
    }

    @Order(3)
    @Test
    @DisplayName("the column REFERENCE cannot be null and is unique")
    void referenceColumn() {
        Schema.Column reference = schema().column("properties", "reference");
        Expect.isTrue(!reference.nullable(),
                "expected the column REFERENCE of PROPERTIES to be NOT NULL");
        Set<String> unique = schema().uniqueColumns("properties");
        Expect.isTrue(unique.contains("REFERENCE"),
                "expected a UNIQUE constraint on the column REFERENCE of PROPERTIES but the unique columns"
                        + " are " + unique);
    }

    @Order(4)
    @Test
    @DisplayName("the address is stored in three columns of the table PROPERTIES")
    void addressIsEmbedded() {
        Expect.isTrue(!schema().hasTable("address") && !schema().hasTable("addresses"),
                "expected no separate table for the address: @Embeddable stores it in PROPERTIES");
        for (String column : new String[] {"street", "zip_code", "city"}) {
            schema().column("properties", column);
        }
    }

    @Order(5)
    @Test
    @DisplayName("the energy class is stored as text, not as a number")
    void energyClassIsText() {
        Schema.Column column = schema().column("properties", "energy_class");
        String type = column.type().toUpperCase();
        boolean number = type.contains("INT") || type.contains("NUMERIC") || type.contains("DECIMAL");
        Expect.isTrue(!number,
                "expected the column ENERGY_CLASS to hold text, \"D\" and not 3"
                        + " (@Enumerated(EnumType.STRING)), but its SQL type is " + column.type());
    }

    @Order(6)
    @Test
    @DisplayName("the surface and the monthly rent are columns of PROPERTIES")
    void ordinaryColumns() {
        schema().column("properties", "surface");
        schema().column("properties", "monthly_rent");
    }

    @Order(7)
    @Test
    @DisplayName("Property is an @Entity mapped to the table properties")
    void propertyIsAnEntity() {
        Class<?> property = Reflect.require(Reflect.PACKAGE + ".model.Property");
        Reflect.requireAnnotation(property, "jakarta.persistence.Entity");
        String table = Reflect.attribute(property, "jakarta.persistence.Table", "name").orElse("");
        Expect.isTrue("properties".equalsIgnoreCase(table),
                "expected @Table(name = \"properties\") on Property but got "
                        + (table.isEmpty() ? "no @Table" : "\"" + table + "\""));
    }

    @Order(8)
    @Test
    @DisplayName("Property has a protected constructor without parameters for Hibernate")
    void protectedConstructor() {
        Class<?> property = Reflect.require(Reflect.PACKAGE + ".model.Property");
        Expect.isTrue(Reflect.hasProtectedNoArgsConstructor(property),
                "expected a protected constructor without parameters in Property (Hibernate needs it)");
    }

    @Order(9)
    @Test
    @DisplayName("Address is annotated with @Embeddable")
    void addressIsEmbeddable() {
        Class<?> address = Reflect.require(Reflect.PACKAGE + ".model.Address");
        Reflect.requireAnnotation(address, "jakarta.persistence.Embeddable");
    }

    @Order(10)
    @Test
    @DisplayName("the H2 console is enabled on the in-memory database realestate")
    void h2ConsoleIsEnabled() {
        String url = context().getEnvironment().getProperty("spring.datasource.url", "");
        Expect.isTrue(url.contains("jdbc:h2:mem:realestate"),
                "expected spring.datasource.url=jdbc:h2:mem:realestate in application.properties but got "
                        + (url.isEmpty() ? "no value" : url));
        Expect.isTrue("true".equalsIgnoreCase(
                        context().getEnvironment().getProperty("spring.h2.console.enabled", "false")),
                "expected spring.h2.console.enabled=true in application.properties");
        Response response = get("/h2-console");
        Expect.isTrue(response.status() != 404,
                "expected the H2 console at /h2-console but got 404: is the dependency"
                        + " org.springframework.boot:spring-boot-h2console in pom.xml?");
    }
}
